/*
  extract.mjs — one-shot helper used to bootstrap the i18n layer.
  Reads the plain-Spanish HTML and writes i18n/template.html + i18n/es.json.
  Not part of the build. Re-run manually if the markup is restructured:
    node tools/extract.mjs
*/
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'liveengines.html');
const OUT_TPL = path.join(ROOT, 'i18n/template.html');
const OUT_ES = path.join(ROOT, 'i18n/es.json');

const ATTRS = ['alt', 'aria-label', 'title', 'placeholder'];
const VOID = new Set(['area','base','br','col','embed','hr','img','input','link','meta','source','track','wbr','path','circle','polyline','rect','line','polygon','use','stop','feturbulence','feBlend','feColorMatrix','feComposite','feFlood','feGaussianBlur','feMerge','feMergeNode','feOffset','feTile']);
const RAW = new Set(['style', 'script']);
// utility/state classes that carry no copy identity
const IGNORED = new Set(['wrap', 'r', 'r-d1', 'r-d2', 'r-d3', 'is-in', 'is-open', 'is-swapped', 'price--feat']);
const HAS_LETTER = /[A-Za-zÀ-ɏ]/;

const src = fs.readFileSync(SRC, 'utf8')
  // liveengines.html is build output — drop its banner so re-extraction stays idempotent
  .replace(/<!-- GENERATED by build\.mjs[^\n]*-->\n?/g, '');

function parseTag(str, start) {
  let i = start + 1;
  if (str[i] === '/') i++;
  const nameStart = i;
  while (i < str.length && /[a-zA-Z0-9:-]/.test(str[i])) i++;
  const name = str.slice(nameStart, i).toLowerCase();
  const attrs = [];
  let selfClose = false;
  while (i < str.length) {
    while (i < str.length && /\s/.test(str[i])) i++;
    if (str[i] === '>') { i++; break; }
    if (str[i] === '/' && str[i + 1] === '>') { selfClose = true; i += 2; break; }
    const m = /^([^\s=/>]+)(\s*=\s*("([^"]*)"|'([^']*)'|([^\s"'>]+)))?/.exec(str.slice(i));
    if (!m) { i++; continue; }
    // exact offsets of the value (inside the quotes) so untouched tags round-trip byte for byte
    let valStart = -1, valEnd = -1;
    if (m[3] !== undefined) { valStart = i + m[0].length - m[3].length + 1; valEnd = valStart + m[3].length - 2; }
    else if (m[4] !== undefined) { valStart = i + m[0].indexOf(m[4], m[1].length); valEnd = valStart + m[4].length; }
    else if (m[5] !== undefined) { valStart = i + m[0].length - m[5].length + 1; valEnd = valStart + m[5].length - 2; }
    attrs.push({ name: m[1], value: m[4] ?? m[5] ?? m[6] ?? null, valStart, valEnd });
    i += m[0].length;
  }
  return { name, attrs, selfClose, end: i };
}

const classesOf = (t) => {
  const c = t.attrs.find(a => a.name === 'class');
  return c?.value ? c.value.trim().split(/\s+/).filter(x => !IGNORED.has(x)) : [];
};
const idOf = (t) => t.attrs.find(a => a.name === 'id')?.value ?? null;
const segOf = (tag, cls, id) => id || cls[cls.length - 1] || tag;

const nodes = [];
const stack = [];
let out = '';
let i = 0;

while (i < src.length) {
  const lt = src.indexOf('<', i);
  if (lt === -1) { out += src.slice(i); break; }

  if (lt > i) {
    const raw = src.slice(i, lt);
    const lead = raw.match(/^\s*/)[0];
    const trail = /\s*$/.exec(raw)[0];
    const core = raw.slice(lead.length, raw.length - trail.length);
    if (core && HAS_LETTER.test(core)) {
      const chain = [];
      for (let k = 0; k < stack.length - 1; k++) {
        const el = stack[k];
        if (el.tag === 'html' || el.tag === 'body') continue;
        if (el.id) chain.push(el.id); else if (el.cls.length) chain.push(el.cls[el.cls.length - 1]);
      }
      chain.push(segOf(stack[stack.length - 1].tag, stack[stack.length - 1].cls, stack[stack.length - 1].id));
      nodes.push({ kind: 'text', chain, value: core });
      out += lead + `\u0000T${nodes.length - 1}\u0000` + trail;
    } else out += raw;
    i = lt;
    continue;
  }

  if (src.startsWith('<!--', lt)) { const e = src.indexOf('-->', lt) + 3; out += src.slice(lt, e); i = e; continue; }
  if (src[lt + 1] === '!' || src[lt + 1] === '?') { const e = src.indexOf('>', lt) + 1; out += src.slice(lt, e); i = e; continue; }

  const closing = src[lt + 1] === '/';
  const t = parseTag(src, lt);
  // self-closing/void elements are never pushed, so their end tag must not pop
  if (closing) {
    if (!VOID.has(t.name)) stack.pop();
    out += src.slice(lt, t.end);
    i = t.end;
    continue;
  }

  const cls = classesOf(t);
  const id = idOf(t);

  // translatable attributes belong to the tag being opened
  let slotIdx = -1;
  for (let k = 0; k < t.attrs.length; k++) {
    const a = t.attrs[k];
    if (!ATTRS.includes(a.name) || !a.value || !HAS_LETTER.test(a.value)) continue;
    if (a.name === 'alt' && a.value === 'LiveEngines') continue;
    const chain = [];
    for (const el of stack) {
      if (el.tag === 'html' || el.tag === 'body') continue;
      if (el.id) chain.push(el.id); else if (el.cls.length) chain.push(el.cls[el.cls.length - 1]);
    }
    chain.push(segOf(t.name, cls, id));
    nodes.push({ kind: 'attr', attr: a.name, chain, value: a.value });
    a.slot = nodes.length - 1;
    slotIdx = k;
    break;
  }
  // emit the tag verbatim, swapping only the one attribute value when needed
  if (slotIdx >= 0) {
    const a = t.attrs[slotIdx];
    out += src.slice(lt, a.valStart) + `\u0000A${a.slot}\u0000` + src.slice(a.valEnd, t.end);
  } else out += src.slice(lt, t.end);

  // <style>/<script> bodies are raw — never tokenize or stack-parse them
  if (RAW.has(t.name) && !t.selfClose) {
    const closeTag = `</${t.name}`;
    const end = src.indexOf(closeTag, t.end);
    const bodyEnd = end === -1 ? src.length : end;
    const after = end === -1 ? src.length : src.indexOf('>', end) + 1;
    out += src.slice(t.end, after);
    i = after;
    continue;
  }

  if (!t.selfClose && !VOID.has(t.name)) stack.push({ tag: t.name, cls, id });
  i = t.end;
}

const seen = new Map();
for (const n of nodes) {
  const base = n.chain.filter(Boolean).join('.') || 'root';
  const c = (seen.get(base) ?? 0) + 1;
  seen.set(base, c);
  n.key = c > 1 ? `${base}.${c}` : base;
}

const flat = {};
for (const n of nodes) flat[n.key] = n.value;

const final = out.replace(/\u0000([TA])(\d+)\u0000/g, (_, k, n) => {
  const node = nodes[+n];
  return k === 'T' ? `{{t:${node.key}}}` : `{{attr:${node.attr}|${node.key}}}`;
});

fs.writeFileSync(OUT_TPL, final);
fs.writeFileSync(OUT_ES, JSON.stringify(flat, null, 2) + '\n');
console.log('nodes extracted:', nodes.length);
console.log('keys with index suffix:', [...seen.values()].filter(c => c > 1).length);
